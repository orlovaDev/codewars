// ❓ УСЛОВИЕ:

// На вашем телефоне уровень заряда аккумулятора отображается в виде ряда из 5 делений. Каждое заполненное деление соответствует 20% заряда. Деление загорается только тогда, когда заряд достигает полных 20%.
// Напишите функцию `battery_bars(percent)`, которая возвращает состояние аккумулятора в виде строки: символ `#` обозначает заполненное деление, а `.` — пустое; вся строка должна быть заключена в квадратные скобки.

// Примеры:
// battery_bars(100)  # => "[#####]"
// battery_bars(70)   # => "[###..]"
// battery_bars(20)   # => "[#....]"
// battery_bars(19)   # => "[.....]"
// battery_bars(0)    # => "[.....]"

// ✅ РЕШЕНИЕ:

function batteryBars(percent) {
  if (percent >= 100) {
    return "[#####]";
  } else if (percent >= 80) {
    return "[####.]";
  } else if (percent >= 60) {
    return "[###..]";
  } else if (percent >= 40) {
    return "[##...]";
  } else if (percent >= 20) {
    return "[#....]";
  } else {
    return "[.....]";
  }
}

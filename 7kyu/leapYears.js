// ❓ УСЛОВИЕ:

//  В этой задаче (ката) нужно просто определить, является ли заданный год високосным.
//  Если вы не знаете правил, вот они: годы, делящиеся на 4, — високосные; однако годы, делящиеся на 100, — невисокосные, за исключением тех, что делятся на 400 (они — високосные).
//  Проверяемые годы находятся в диапазоне 1600 ≤ year ≤ 4000.

// ✅ РЕШЕНИЕ:

function isLeapYear(year) {
  return year % 400 === 0 || (year % 4 === 0 && year % 100 !== 0);
}